_POOL = {}


def _sha16(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 24), b""):
            h.update(b)
    return h.hexdigest()[:16]


def _pool(Nr, check=True):
    """(H memory-mapped (pairs, Nr, Nt) complex64, {'fit' | 'val' | 'test': pair indices}), loaded once per process."""
    if Nr not in _POOL:
        d = os.path.join(POOL_DIR, f"dmc_Nr{Nr}")
        hp, mp = os.path.join(d, "H.npy"), os.path.join(d, "split.npy")
        if check:
            if Nr not in POOL_SHA:
                raise ValueError(f"DMC pool is pinned for Nr in {sorted(POOL_SHA)} only, not Nr={Nr} (dmimo.py docstring)")
            got = (_sha16(hp), _sha16(mp))
            if got != POOL_SHA[Nr]:
                raise ValueError(f"DMC pool {d} has sha {got}, pinned {POOL_SHA[Nr]}: rebuild with dmimo_build.py or restore")
        split = np.load(mp)                                                  # 0 fit / 1 validation / 2 test per pair
        _POOL[Nr] = (np.load(hp, mmap_mode="r"), {k: np.where(split == c)[0] for c, k in enumerate(("fit", "val", "test"))})
    return _POOL[Nr]


def _which(rng, prior, Nr):
    """Pool of a stream, from its seed layout: common.train_rng = [SEED, TBID, which, PID, Nr], trial_rng = [SEED, TBID, PID,
    Nr, T, Tp, snr + 100]."""
    import common as C
    e = rng.bit_generator.seed_seq.entropy
    e = list(e) if isinstance(e, (list, tuple)) else [e]
    head = [C.SEED, C.TBID["D2"]]
    if len(e) == 5 and e[:2] == head and e[3:] == [C.PID[prior], Nr] and e[2] in (7, 8, 10):
        return {7: "fit", 8: "val", 10: "test"}[e[2]]
    if len(e) == 7 and e[:2] == head and e[2:4] == [C.PID[prior], Nr]:
        return "test"
    if len(e) == 5 and e[:4] == [20260930, C.TBID["D2"], C.PID[prior], Nr]:      # sparse_tune.py development stream
        return "test"
    raise ValueError(f"DMC draws only from common.train_rng (streams 7 / 8 / 10), common.trial_rng or sparse_tune's stream of prior {prior}, Nr={Nr}; "
                     f"got seed layout {e} -- the block split cannot be honoured for an unknown stream")


class DMGen:
    """DMC generator with the D2Gen slots the pipeline uses: .sample(rng), .sample_vecs(rng, n), .prior (None: no density,
    like D2), .name ("D2": it runs under testbed D2), .kind, .Nr/.Nt/.N."""
    name = "D2"
    prior = None

    def __init__(self, prior, Nr, Nt, raw=False):
        assert prior in PRIORS, f"DeepMIMO priors are {PRIORS}, got {prior!r}"
        if not raw and (prior, Nr, Nt) not in P_RAW:
            raise ValueError(f"{prior} is calibrated for {sorted(P_RAW)} only, not Nr={Nr} x Nt={Nt}: another array needs "
                             "dmimo_build.py, `python dmimo.py calibrate <Nr>` and a decision (dmimo.py docstring)")
        self.kind = prior
        self.Nr, self.Nt, self.N = Nr, Nt, Nr * Nt
        self.H, self.idx = _pool(Nr, check=not raw)
        assert self.H.shape[1:] == (Nr, Nt), self.H.shape
        self.s = 1.0 if raw else float(np.sqrt(P_RAW[(prior, Nr, Nt)]))      # raw=True: calibration only

    def _draw(self, rng, n):
        """n blocks (n, Nr, Nt) complex128, normalised."""
        w = _which(rng, self.kind, self.Nr)
        ix = self.idx[w]
        if w == "test":
            i = ix[rng.integers(0, len(ix), n)]
        else:
            if n > len(ix):
                raise ValueError(f"DMC {w} pool has {len(ix)} pairs, {n} distinct pairs requested")
            i = ix[rng.permutation(len(ix))[:n]]
        return np.asarray(self.H[i], dtype=complex) / self.s

    def sample(self, rng):
        return self._draw(rng, 1)[0]

    def sample_vecs(self, rng, n):
        """(n, Nr*Nt) complex128, row i = vec(H_i) column-major (== H.reshape(-1, order='F'))."""
        return self._draw(rng, n).transpose(0, 2, 1).reshape(n, self.N)


def ensemble_sides_dm(prior, Nr, Nt):
    """(Rt, Rr, informative) -- same contract as d2.ensemble_sides_d2; Rt, Rr are the frozen training-set estimates,
    informative = the T2b rule erank(Rt) < 0.9 Nt."""
    import d2
    assert prior in PRIORS, prior
    if (prior, Nr, Nt) not in RT:
        raise ValueError(f"{prior} ensemble sides exist for {sorted(RT)} only, not Nr={Nr} x Nt={Nt}")
    Rt = RT[(prior, Nr, Nt)]
    return Rt, RR[(prior, Nr, Nt)], bool(d2._erank(np.linalg.eigvalsh(Rt)) < d2.T2B_ERANK_FRAC * Nt)


def calibrate(prior, Nr, Nt):
    """-> (P_RAW, Rt, Rr, sha) from the raw training set (stream 7, N_CAL); sha is that of the NORMALISED vec set."""
    import common as C
    H = DMGen(prior, Nr, Nt, raw=True)._draw(C.train_rng("D2", prior, Nr, 7), N_CAL)
    n = len(H)
    p = float(np.mean(np.sum(H.real ** 2 + H.imag ** 2, (1, 2)))) / (Nr * Nt)
    Hn = H / float(np.sqrt(p))
    Rt = np.einsum("nab,nac->bc", Hn.conj(), Hn) / (n * Nr)
    Rr = np.einsum("nab,ncb->ac", Hn, Hn.conj()) / (n * Nt)
    Rt, Rr = 0.5 * (Rt + Rt.conj().T), 0.5 * (Rr + Rr.conj().T)
    sha = hashlib.sha256(np.ascontiguousarray(Hn.transpose(0, 2, 1).reshape(n, Nr * Nt)).tobytes()).hexdigest()[:16]
    return p, Rt, Rr, sha


