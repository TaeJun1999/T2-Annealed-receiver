"""conf/code/dmimo_build.py -- ONE-TIME builder of the DeepMIMO channel pool behind prior 'DMC' (conf/code/dmimo.py).

User decision 2026-10-10 CDT: receiver BLER on DeepMIMO (the phase-0 "6 cities, block split" configuration,
conf/results/review_next/testbed2_phase0/report_deepmimo.md) with the channels generated by DeepMIMO's OWN generator
(dataset.compute_channels), not by array code of ours.  The pool is a fixed file under ~/data (not in git); dmimo.py pins its
sha256, so a rebuild that differs by one bit is refused.

Source   : DeepMIMO v4.0.5 (pip --no-deps --target ~/data/deepmimo/site; numpy 2.5.2), scenarios (Wireless InSite 3.3, 28 GHz)
           city_0_newyork_28, city_6_miami_28, city_1_losangeles_28, city_2_chicago_28, city_3_houston_28, city_4_phoenix_28
           (the phase-0 order), dm.load(s, max_paths=25): every TX set (BS) x the RX grid.
Pairs    : one pair = (scenario, BS, grid user) with at least one path; users without a path are dropped.
Channels : dataset.compute_channels(ChannelParameters): freq_domain, selected_subcarriers [0] (delay phase exp(0) = 1, i.e.
           the narrowband channel at the carrier), num_paths 25, isotropic elements, half-wavelength spacing;
           BS  = 8 x 1 panel (horizontal ULA on the local y axis), rotation [0, 0, yaw_BS], yaw_BS = azimuth from the BS to the
                 centroid of that BS's pairs (a sector facing its users; the phase-0 rule);
           UE  = 4 x 1 panel, rotation [0, 0, yaw_UE], yaw_UE ~ U[-180, 180) deg per pair, drawn ONCE here (frozen);
           uplink by reciprocity: H[a, b] = BS antenna a, UE antenna b = compute_channels(...)[user, b, a, 0];
           per-pair normalisation: H / sqrt(sum of that pair's linear path powers)  (pathloss / shadowing removed, as phase 0);
           complex64 as DeepMIMO returns it (cast to complex128 by dmimo.DMGen).
Split    : 20 m position tiles per scenario (floor(xy / 20)); tiles are permuted and taken until they hold >= 15 % of the pairs
           -> TEST tiles (a tile is on one side for every BS that sees it); of the remaining TRAIN-tile pairs a frozen random
           N_VAL_POOL are the validation pool, the rest the fit pool (split.npy: 0 / 1 / 2 = fit / validation / test per pair).
           dmimo.DMGen maps streams onto these three pools.
Seed     : default_rng([SEED, TBID['D2'], 12, PID['DMC']]) -- yaws (scenario by scenario, BS by BS), tiles, validation pool.

usage: cd ~/data/deepmimo && ~/miniforge3/envs/torch/bin/python ~/t2/conf/code/dmimo_build.py [Nr]     (cwd = where
       deepmimo_scenarios/ lives; DeepMIMO resolves it relative to the working directory)
"""
import hashlib
import os
import sys
import time

import numpy as np

SITE = os.path.expanduser("~/data/deepmimo/site")
SCEN = ("city_0_newyork_28", "city_6_miami_28", "city_1_losangeles_28", "city_2_chicago_28", "city_3_houston_28",
        "city_4_phoenix_28")
MAX_PATHS = 25
TILE = 20.0                              # m
TEST_SHARE = 0.15
N_VAL_POOL = 20000
NT = 4


def out_dir(Nr):
    return os.path.expanduser(f"~/data/deepmimo/dmc_Nr{Nr}")


def sha16(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 24), b""):
            h.update(b)
    return h.hexdigest()[:16]


def build(Nr):
    sys.path.insert(0, SITE)
    import deepmimo as dm
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import common as C
    rng = np.random.default_rng([C.SEED, C.TBID["D2"], 12, C.PID["DMC"]])
    Hs, scen, bs, pos, los, npath, yaw, bsyaw = [], [], [], [], [], [], [], []
    for si, s in enumerate(SCEN):
        ds = dm.load(s, max_paths=MAX_PATHS)
        for bi, d in enumerate(ds if type(ds).__name__ == "MacroDataset" else [ds]):
            n_ue = len(d.rx_pos)
            ok = np.asarray(d.num_paths) > 0
            cen = np.asarray(d.rx_pos)[ok].mean(0) - np.asarray(d.tx_pos).reshape(-1, 3)[0]
            by = float(np.degrees(np.arctan2(cen[1], cen[0])))
            uy = rng.uniform(-180.0, 180.0, n_ue)                      # one draw per grid user, valid or not (fixed order)
            p = dm.ChannelParameters()
            p.bs_antenna.shape = np.array([Nr, 1]); p.bs_antenna.rotation = np.array([0.0, 0.0, by])
            p.ue_antenna.shape = np.array([NT, 1])
            p.ue_antenna.rotation = np.column_stack([np.zeros(n_ue), np.zeros(n_ue), uy])
            p.num_paths = MAX_PATHS
            p.freq_domain = True
            p.ofdm.selected_subcarriers = np.array([0])
            H = np.asarray(d.compute_channels(p))[ok, :, :, 0]         # (pairs, UE Nt, BS Nr)
            pw = np.nansum(np.asarray(d.power_linear)[ok], 1)
            H = H.transpose(0, 2, 1) / np.sqrt(pw)[:, None, None]      # uplink (pairs, Nr, Nt), sum of path powers = 1
            assert H.shape[1:] == (Nr, NT) and np.isfinite(H).all(), (s, bi, H.shape)
            Hs.append(H.astype(np.complex64)); scen.append(np.full(ok.sum(), si)); bs.append(np.full(ok.sum(), bi))
            pos.append(np.asarray(d.rx_pos)[ok]); los.append(np.asarray(d.los)[ok]); npath.append(np.asarray(d.num_paths)[ok])
            yaw.append(uy[ok]); bsyaw.append(np.full(ok.sum(), by))
            print(f"  {s} BS {bi}: {ok.sum()} / {n_ue} pairs, BS yaw {by:+.1f} deg", flush=True)
    H = np.concatenate(Hs); scen, bs, pos, los, npath, yaw, bsyaw = map(np.concatenate, (scen, bs, pos, los, npath, yaw, bsyaw))
    n = len(H)
    # block split (phase-0 rule): tiles keyed by (scenario, floor(xy / TILE))
    tile = np.floor(pos[:, :2] / TILE).astype(np.int64)
    key = tile[:, 0] * 100003 + tile[:, 1] + 10 ** 12 * scen
    uk, inv = np.unique(key, return_inverse=True)
    order = rng.permutation(len(uk)); cnt = np.bincount(inv)
    tsel = order[: np.searchsorted(np.cumsum(cnt[order]), TEST_SHARE * n) + 1]
    istest = np.isin(inv, tsel)
    idx_test = np.where(istest)[0]; tr = np.where(~istest)[0]
    v = np.zeros(len(tr), bool); v[rng.permutation(len(tr))[:N_VAL_POOL]] = True
    idx_val, idx_fit = tr[v], tr[~v]
    assert not set(key[idx_test]) & set(key[tr]), "a tile is on both sides of the split"
    o = out_dir(Nr); os.makedirs(o, exist_ok=True)
    split = np.zeros(n, np.int8); split[idx_val] = 1; split[idx_test] = 2      # 0 fit / 1 validation / 2 test
    np.save(os.path.join(o, "H.npy"), H)
    np.save(os.path.join(o, "split.npy"), split)                             # .npy is byte-deterministic (an .npz is not)
    np.savez(os.path.join(o, "meta.npz"), scen=scen, bs=bs, pos=pos, los=los, npath=npath, yaw=yaw, bsyaw=bsyaw, key=key,
             scenarios=np.array(SCEN))                                       # descriptive only, not pinned
    return o, n, len(idx_fit), len(idx_val), len(idx_test), len(uk), len(tsel)


if __name__ == "__main__":
    Nr = int(sys.argv[1]) if len(sys.argv) > 1 else 8
    t0 = time.time()
    o, n, nf, nv, nt, ntile, ntt = build(Nr)
    print(f"# dmimo_build Nr={Nr} x Nt={NT}: {n} pairs = fit {nf} + val {nv} + test {nt} (test share {nt / n:.4f}); "
          f"tiles {ntile} ({ntt} test); {time.time() - t0:.0f} s")
    print(f"POOL_SHA[{Nr}] = ({sha16(os.path.join(o, 'H.npy'))!r}, {sha16(os.path.join(o, 'split.npy'))!r})")
    for z in sorted(f for f in os.listdir("deepmimo_scenarios") if f.endswith(".zip")):
        print(f"# zip {z} sha256[:16] {sha16(os.path.join('deepmimo_scenarios', z))}")
